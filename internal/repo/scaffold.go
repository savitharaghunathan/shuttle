package repo

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"gopkg.in/yaml.v3"
)

type scaffoldConfig struct {
	DefaultWorker  string                 `yaml:"default_worker"`
	WorkRoot       string                 `yaml:"work_root"`
	Concurrency    int                    `yaml:"concurrency"`
	DefaultTimeout string                 `yaml:"default_timeout"`
	Test           scaffoldStage          `yaml:"test"`
	OpenPR         scaffoldStage          `yaml:"open_pr"`
	Ship           scaffoldStage          `yaml:"ship"`
	Workers        map[string]scaffoldWorker `yaml:"workers"`
}

type scaffoldStage struct {
	Command []string `yaml:"command"`
}

type scaffoldWorker struct {
	Bin  string   `yaml:"bin,omitempty"`
	Args []string `yaml:"args,omitempty"`
}

// WriteShuttleYAMLIfAbsent creates shuttle.yaml with detected defaults when missing.
func WriteShuttleYAMLIfAbsent(repoPath string, testCmd []string) error {
	path := filepath.Join(repoPath, "shuttle.yaml")
	if _, err := os.Stat(path); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("stat shuttle.yaml: %w", err)
	}

	cfg := scaffoldConfig{
		DefaultWorker:  "cursor",
		WorkRoot:       ".shuttle",
		Concurrency:    1,
		DefaultTimeout: "30m",
		Test:           scaffoldStage{Command: testCmd},
		OpenPR: scaffoldStage{Command: []string{
			"gh", "pr", "create", "--fill",
		}},
		Ship: scaffoldStage{Command: []string{"echo", "ship skipped"}},
		Workers: map[string]scaffoldWorker{
			"shell": {Bin: "/bin/bash"},
			"claude": {
				Bin: "claude",
				Args: []string{
					"{{if .Model}}--model{{end}}", "{{.Model}}",
					"-p", "{{.Prompt}}",
				},
			},
			"cursor": {
				Bin: "cursor-agent",
				Args: []string{
					"--trust", "--yolo",
					"{{if .Model}}--model{{end}}", "{{.Model}}",
					"--print", "{{.Prompt}}",
				},
			},
			"codex": {
				Bin: "codex",
				Args: []string{
					"{{if .Model}}--model{{end}}", "{{.Model}}",
					"exec", "{{.Prompt}}",
				},
			},
			"opencode": {
				Bin: "opencode",
				Args: []string{
					"{{if .Model}}--model{{end}}", "{{.Model}}",
					"run", "{{.Prompt}}",
				},
			},
		},
	}

	data, err := yaml.Marshal(cfg)
	if err != nil {
		return fmt.Errorf("marshal shuttle.yaml: %w", err)
	}

	header := "# Generated by shuttle import repo. Edit freely.\n"
	if err := os.WriteFile(path, []byte(header+string(data)), 0o644); err != nil {
		return fmt.Errorf("write shuttle.yaml: %w", err)
	}
	return nil
}

// CloneURL returns the canonical HTTPS clone URL for owner/name.
func CloneURL(owner, name string) string {
	return fmt.Sprintf("https://github.com/%s/%s.git", owner, name)
}

// IsGitRepo reports whether path contains a .git directory.
func IsGitRepo(path string) bool {
	_, err := os.Stat(filepath.Join(path, ".git"))
	return err == nil
}

// NormalizeRemoteURL returns a stable https URL for registry storage.
func NormalizeRemoteURL(owner, name string) string {
	return strings.TrimSuffix(CloneURL(owner, name), ".git")
}
